import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { demoCatalog, defaultSettings } from '../lib/contracts';
import { entitlements } from '../lib/entitlements';
const base = process.env.QA_URL || 'http://127.0.0.1:4187';
if (!/^(localhost|127\.0\.0\.1)$/.test(new URL(base).hostname)) throw Error('Local fixture only');
const browser = await chromium.launch();
await mkdir('outputs/owner-navigation-qa', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.clock.install();
  const draft = structuredClone(demoCatalog);
  draft.name = 'QA FICTICIO · Navegación dueño';
  draft.nameConfirmed = true;
  let revision = 1;
  let failSave = false;
  let reads = 0;
  let features = ['orders', 'promotions'];
  let permissions = entitlements({ active: true, plan: 'premium' });
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith('/session')) return route.fulfill({ json: { authenticated: true, configured: true, runtime: 'cloud', csrfToken: 'qa-csrf' } });
    if (path.endsWith('/state')) { reads++; return route.fulfill({ json: { restaurantId: '11111111-1111-4111-8111-111111111111', revision, draft, settings: defaultSettings, published: null, role: 'owner', features, entitlements: permissions, businessReady: false } }); }
    if (path.endsWith('/editor-version')) return route.fulfill({ json: { revision, features, entitlements: permissions } });
    if (path.endsWith('/draft')) return route.fulfill({ status: failSave ? 409 : 200, json: failSave ? { error: 'Hay una actualización más reciente. Revisa los cambios antes de guardar.' } : { ok: true } });
    if (path.includes('/reports/orders')) return route.fulfill({ json: { orders: [], totalOrders: 0, totalCents: 0 } });
    return route.fulfill({ json: {} });
  });
  await page.goto(base + '/r/11111111-1111-4111-8111-111111111111');
  await page.getByRole('button', { name: 'Añadir plato', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click();
  const labels = ['Identidad del restaurante', 'Presentación', 'Contacto público', 'Horarios', 'Colores de la carta', 'Seguridad y sesiones', 'Respaldos'];
  const summaries = page.locator('details > summary:visible');
  await expect(summaries.first()).toBeVisible();
  for (const label of labels) {
    const summary = page.locator('details > summary').filter({ hasText: label }).first();
    const details = summary.locator('..');
    const wasOpen = await details.getAttribute('open');
    await summary.click();
    if (wasOpen === null) await expect(details).toHaveAttribute('open', '');
    else await expect(details).not.toHaveAttribute('open', '');
    await summary.click();
  }
  await page.screenshot({ path: 'outputs/owner-navigation-qa/settings-disclosures.png', fullPage: true });
  await page.getByRole('button', { name: 'Pedidos', exact: true }).click();
  await page.evaluate(() => history.back());
  await expect(summaries.first()).toBeVisible();
  await page.evaluate(() => history.back());
  await page.getByRole('button', { name: 'Añadir plato', exact: true }).waitFor();
  const handleNativeBack = () => page.evaluate(() => (window as Window & { qrMenuHandleBack?: () => boolean }).qrMenuHandleBack?.());
  if (await handleNativeBack() !== false) throw Error('Native back must release navigation only at owner root depth zero');
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click();
  if (await handleNativeBack() !== true) throw Error('Native back must consume a nested owner tab');
  await page.getByRole('button', { name: 'Añadir plato', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Añadir plato', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  if (await handleNativeBack() !== true) throw Error('Native back must consume an editing dialog');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  if (await handleNativeBack() !== false) throw Error('Closing an editor must not leave the owner root');
  await page.locator('.availability').first().click();
  await expect(page.getByRole('button', { name: 'Guardar borrador', exact: true })).toBeEnabled();
  revision++;
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  const reload = page.getByRole('button', { name: 'Recargar app', exact: true });
  await expect(reload).toBeVisible();
  const beforeReads = reads;
  page.once('dialog', dialog => void dialog.dismiss());
  await reload.click();
  await expect(page.getByRole('button', { name: 'Guardar borrador', exact: true })).toBeEnabled();
  if (reads !== beforeReads) throw Error('Canceling reload unexpectedly read and replaced draft');
  await page.screenshot({ path: 'outputs/owner-navigation-qa/external-change-draft-preserved.png', fullPage: false });
  page.once('dialog', dialog => void dialog.accept());
  await reload.click();
  await page.getByRole('button', { name: 'Añadir plato', exact: true }).waitFor();
  await expect(page.getByRole('button', { name: 'Guardar borrador', exact: true })).toHaveCount(0);
  if (reads <= beforeReads) throw Error('Accepted reload failed to fetch current state');
  await page.locator('.availability').first().click();
  failSave = true;
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click();
  await expect(reload).toBeVisible();
  await expect(page.getByRole('button', { name: 'Guardar borrador', exact: true })).toBeEnabled();
  await page.screenshot({ path: 'outputs/owner-navigation-qa/conflict-draft-preserved.png', fullPage: false });
  // A creator change to permissions is detected even without a revision change.
  page.once('dialog', dialog => void dialog.accept());
  await reload.click();
  await page.getByRole('button', { name: 'Añadir plato', exact: true }).waitFor();
  features = ['orders']; permissions = entitlements({ active: true, plan: 'basic' });
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(reload).toBeVisible();
  await reload.click();
  await page.getByRole('button', { name: 'Añadir plato', exact: true }).waitFor();
  revision++;
  await page.clock.fastForward(31_000);
  await expect(reload).toBeVisible();
  await writeFile('outputs/owner-navigation-qa/result.json', JSON.stringify({ checkedAt: new Date().toISOString(), passed: ['settings-disclosures', 'back-two-tabs', 'native-back-root-false', 'native-back-nested-tab-true', 'native-back-editor-dialog-consumed', 'external-revision-focus', 'cancel-reload-preserves-draft', 'accept-reload-fetches-state', '409-preserves-draft', 'creator-features-and-entitlements-change', '30-second-poll-with-browser-clock'], limitation: 'Chromium localhost mocked APIs and virtual timer; native callback contract only, no physical Android or production authentication' }, null, 2));
  console.log('Owner navigation and external change QA passed');
} finally { await browser.close(); }
